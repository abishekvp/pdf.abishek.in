"use client";

import { PDFDocument, rgb, StandardFonts } from "pdf-lib";

/** Generate a realistic, attractive multi-page sample PDF */
export async function createSamplePdf(
  title: string = "Sample Report - Financial Q4 Overview",
  pagesCount: number = 3
): Promise<File> {
  const pdfDoc = await PDFDocument.create();
  const fontBold = await pdfDoc.embedFont(StandardFonts.HelveticaBold);
  const fontRegular = await pdfDoc.embedFont(StandardFonts.Helvetica);

  for (let i = 1; i <= pagesCount; i++) {
    const page = pdfDoc.addPage([595.28, 841.89]); // A4
    const { width, height } = page.getSize();

    // Top banner
    page.drawRectangle({
      x: 0,
      y: height - 100,
      width: width,
      height: 100,
      color: rgb(0.88, 0.11, 0.28), // Crimson brand color
    });

    page.drawText(title, {
      x: 40,
      y: height - 60,
      size: 20,
      font: fontBold,
      color: rgb(1, 1, 1),
    });

    page.drawText(`Page ${i} of ${pagesCount} • Generated by pdf.abishek.in`, {
      x: 40,
      y: height - 85,
      size: 10,
      font: fontRegular,
      color: rgb(1, 0.85, 0.85),
    });

    // Content section
    let y = height - 150;

    page.drawText(`Section ${i}: Executive Performance & Analytics`, {
      x: 40,
      y,
      size: 16,
      font: fontBold,
      color: rgb(0.1, 0.15, 0.25),
    });

    y -= 30;

    const sampleParagraphs = [
      "This document was created automatically as a high-fidelity demonstration file for testing PDF compression, conversion, formatting, and manipulation tools.",
      "The global digital transformation has accelerated demand for secure, client-side document processing where private documents never touch an untrusted cloud server.",
      "All operations are performed 100% locally in your browser with zero latency and complete privacy.",
      "Key performance indicators demonstrate a 42% increase in productivity when using modern web tooling with full-screen high-visibility controls.",
    ];

    for (const p of sampleParagraphs) {
      page.drawText(p, {
        x: 40,
        y,
        size: 11,
        font: fontRegular,
        color: rgb(0.2, 0.25, 0.35),
      });
      y -= 25;
    }

    // A decorative stats box
    y -= 20;
    page.drawRectangle({
      x: 40,
      y: y - 80,
      width: width - 80,
      height: 90,
      color: rgb(0.95, 0.96, 0.98),
      borderColor: rgb(0.8, 0.85, 0.9),
      borderWidth: 1,
    });

    page.drawText("Quarterly Metrics & Confidence Score", {
      x: 60,
      y: y - 25,
      size: 12,
      font: fontBold,
      color: rgb(0.1, 0.15, 0.25),
    });

    page.drawText(
      `Efficiency: 99.8%  |  Compression Index: High  |  Status: Verified  |  Timestamp: ${new Date().toLocaleDateString()}`,
      {
        x: 60,
        y: y - 50,
        size: 10,
        font: fontRegular,
        color: rgb(0.3, 0.35, 0.45),
      }
    );

    // Footer
    page.drawLine({
      start: { x: 40, y: 50 },
      end: { x: width - 40, y: 50 },
      thickness: 1,
      color: rgb(0.85, 0.85, 0.85),
    });

    page.drawText(`Confidential • pdf.abishek.in • Page ${i} of ${pagesCount}`, {
      x: 40,
      y: 35,
      size: 9,
      font: fontRegular,
      color: rgb(0.5, 0.5, 0.5),
    });
  }

  const pdfBytes = await pdfDoc.save();
  return new File([pdfBytes.buffer as ArrayBuffer], `${title.toLowerCase().replace(/[^a-z0-9]/g, "-")}.pdf`, {
    type: "application/pdf",
  });
}

/** Generate a sample image file (PNG/JPEG) */
export function createSampleImage(name = "sample-photo.jpg", width = 1200, height = 800): Promise<File> {
  return new Promise((resolve) => {
    const canvas = document.createElement("canvas");
    canvas.width = width;
    canvas.height = height;
    const ctx = canvas.getContext("2d")!;

    // Gradient background
    const grad = ctx.createLinearGradient(0, 0, width, height);
    grad.addColorStop(0, "#4f46e5");
    grad.addColorStop(0.5, "#e11d48");
    grad.addColorStop(1, "#06b6d4");
    ctx.fillStyle = grad;
    ctx.fillRect(0, 0, width, height);

    // Some decorative shapes
    ctx.fillStyle = "rgba(255, 255, 255, 0.15)";
    ctx.beginPath();
    ctx.arc(width * 0.3, height * 0.4, 200, 0, Math.PI * 2);
    ctx.fill();

    ctx.fillStyle = "rgba(255, 255, 255, 0.2)";
    ctx.beginPath();
    ctx.arc(width * 0.75, height * 0.65, 260, 0, Math.PI * 2);
    ctx.fill();

    // Text
    ctx.fillStyle = "#ffffff";
    ctx.font = "bold 56px sans-serif";
    ctx.textAlign = "center";
    ctx.fillText("High Definition Sample Image", width / 2, height / 2 - 20);

    ctx.font = "normal 28px sans-serif";
    ctx.fillText("Ready to convert into high-quality PDF • pdf.abishek.in", width / 2, height / 2 + 40);

    canvas.toBlob(
      (blob) => {
        resolve(new File([blob!], name, { type: "image/jpeg" }));
      },
      "image/jpeg",
      0.95
    );
  });
}

